package io.securebox.core.domain.security

import java.io.File
import java.nio.file.Files
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class Sha256Test {
    @Test
    fun hashesKnownVector() {
        // NIST test vector for "abc".
        assertEquals(
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad",
            Sha256.of("abc".toByteArray()),
        )
    }

    @Test
    fun hashesFileAndMatchesStreamingDigest() {
        val file = Files.createTempFile("securebox", ".bin").toFile()
        try {
            file.writeBytes(ByteArray(200_000) { index -> (index % 251).toByte() })
            assertEquals(Sha256.of(file.readBytes()), Sha256.of(file))
        } finally {
            file.delete()
        }
    }

    @Test
    fun normalisesAndComparesCaseInsensitively() {
        val uppercase = "BA7816BF8F01CFEA414140DE5DAE2223B00361A396177A9CB410FF61F20015AD"
        assertTrue(Sha256.matches(uppercase, Sha256.of("abc".toByteArray())))
        assertTrue(Sha256.matches("sha256:${uppercase.lowercase()}", Sha256.of("abc".toByteArray())))
        assertFalse(Sha256.matches(uppercase, Sha256.of("abd".toByteArray())))
    }

    @Test
    fun parsesSha256SumsFormats() {
        val content =
            """
            # generated by CI
            1111111111111111111111111111111111111111111111111111111111111111  securebox-universal-release.apk
            2222222222222222222222222222222222222222222222222222222222222222 *securebox-arm64-v8a-release.apk
            """.trimIndent()

        assertEquals(
            "1111111111111111111111111111111111111111111111111111111111111111",
            Sha256.parseChecksumFile(content, "securebox-universal-release.apk"),
        )
        assertEquals(
            "2222222222222222222222222222222222222222222222222222222222222222",
            Sha256.parseChecksumFile(content, "securebox-arm64-v8a-release.apk"),
        )
        assertNull(Sha256.parseChecksumFile(content, "missing.apk"))
        assertNull(Sha256.parseChecksumFile("not-a-hash  file.apk", "file.apk"))
    }

    @Test
    fun readsDigestOfEmptyFile() {
        val file = File.createTempFile("securebox-empty", ".bin")
        try {
            assertEquals("e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855", Sha256.of(file))
        } finally {
            file.delete()
        }
    }
}
